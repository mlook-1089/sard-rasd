export function pagesForHizb(hizb: number): number[] {
  const range = HIZB_PAGES[hizb];
  if (!range) return [];
  const [start, end] = range;
  const out: number[] = [];
  for (let p = start; p <= end; p++) out.push(p);
  return out;
}
